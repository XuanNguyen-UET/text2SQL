def parse_quoted_identifier(line: str) -> str | None:
    line = line.strip()

    if not line:
        return None

    if line[0] == '"':
        end = line.find('"', 1)
        return line[1:end] if end > 1 else None

    match = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s+", line)
    return match.group(1) if match else None


def extract_schema_from_ddl(ddl: str) -> dict[str, set[str]]:
    schema = {}
    pattern = r'CREATE\s+TABLE\s+"([^"]+)"\s*\((.*?)\)\s*;'

    for match in re.finditer(pattern, ddl, flags=re.IGNORECASE | re.DOTALL):
        table_name = match.group(1)
        body = match.group(2)
        columns = set()

        for raw_line in body.splitlines():
            line = raw_line.strip().rstrip(",")
            upper = line.upper()

            if not line:
                continue

            if upper.startswith(("PRIMARY KEY", "FOREIGN KEY", "CONSTRAINT", "CHECK", "UNIQUE", "--")):
                continue

            column_name = parse_quoted_identifier(line)
            if column_name:
                columns.add(column_name)

        schema[table_name] = columns

    return schema


def validate_mini_ddl_against_profile(profile, ddl):
    errors = []
    parsed_schema = extract_schema_from_ddl(ddl)

    if not parsed_schema:
        errors.append("cannot_parse_create_table")

    profile_tables = profile.get("tables", {})

    for table_name, columns in parsed_schema.items():
        if table_name not in profile_tables:
            errors.append(f"unknown_table:{table_name}")
            continue

        real_columns = set(profile_tables[table_name].get("columns", {}).keys())
        for column_name in columns:
            if column_name not in real_columns:
                errors.append(f"unknown_column:{table_name}.{column_name}")

    if "CREATE TABLE" not in ddl.upper():
        errors.append("missing_create_table")

    if "samples:" not in ddl.lower() and "sample" not in ddl.lower():
        errors.append("missing_sample_value_comments")

    return {
        "valid": len(errors) == 0,
        "errors": errors,
        "parsed_schema": {table: sorted(cols) for table, cols in parsed_schema.items()},
    }


