def parse_column_descriptions(table_info: dict[str, Any]) -> dict[str, str]:
    descriptions = {}

    for raw_desc in table_info.get("table_description", []) or []:
        match = re.search(r"original_column_name:\s*([^|]+)", str(raw_desc))
        if match:
            descriptions[match.group(1).strip()] = normalize_space(raw_desc)

    return descriptions


def iter_columns(profile: dict[str, Any]):
    for table_name, table_info in profile.get("tables", {}).items():
        descriptions = parse_column_descriptions(table_info)

        for column_name, column_info in table_info.get("columns", {}).items():
            yield {
                "table": table_name,
                "column": column_name,
                "qualified": f"{table_name}.{column_name}",
                "column_info": column_info,
                "description": descriptions.get(column_name, ""),
            }


def get_explicit_primary_key_map(profile: dict[str, Any]) -> dict[str, set[str]]:
    result = defaultdict(set)

    for qualified_name in profile.get("explicit_primary_keys", []) or []:
        table_name, column_name = split_qualified_name(qualified_name)
        result[table_name].add(column_name)

    return dict(result)


def get_explicit_foreign_key_edges(profile: dict[str, Any]) -> list[dict[str, str]]:
    edges = []

    for item in profile.get("explicit_foreign_keys", []) or []:
        source_table, source_column = split_qualified_name(item["source"])
        target_table, target_column = split_qualified_name(item["target"])

        edges.append(
            {
                "source_table": source_table,
                "source_column": source_column,
                "target_table": target_table,
                "target_column": target_column,
                "source": item["source"],
                "target": item["target"],
            }
        )

    return edges

@dataclass
class BM25Document:
    key: str
    tokens: list[str]
    metadata: dict[str, Any]


class BM25Index:
    def __init__(self, documents: list[BM25Document], k1: float = 1.5, b: float = 0.75):
        self.documents = documents
        self.k1 = k1
        self.b = b
        self.doc_freq = Counter()
        self.term_freqs = []
        self.doc_lengths = []

        for doc in documents:
            tf = Counter(doc.tokens)
            self.term_freqs.append(tf)
            self.doc_lengths.append(len(doc.tokens))

            for term in tf.keys():
                self.doc_freq[term] += 1

        self.num_docs = len(documents)
        self.avg_doc_length = sum(self.doc_lengths) / max(self.num_docs, 1)

    def score(self, query: str) -> list[tuple[float, BM25Document]]:
        query_terms = tokenize(query)
        scores = []

        for index, doc in enumerate(self.documents):
            score = 0.0
            doc_length = self.doc_lengths[index]
            tf = self.term_freqs[index]

            for term in query_terms:
                if term not in tf:
                    continue

                df = self.doc_freq.get(term, 0)
                idf = math.log(1 + (self.num_docs - df + 0.5) / (df + 0.5))
                numerator = tf[term] * (self.k1 + 1)
                denominator = tf[term] + self.k1 * (
                    1 - self.b + self.b * doc_length / max(self.avg_doc_length, 1e-9)
                )

                score += idf * numerator / denominator

            scores.append((score, doc))

        return sorted(scores, key=lambda item: item[0], reverse=True)


def build_column_document(column: dict[str, Any]) -> str:
    sample_values = column["column_info"].get("sample_values", []) or []
    sample_text = " ".join(str(value) for value in sample_values[:SAMPLE_VALUES_PER_COLUMN])

    return " ".join(
        [
            column["table"],
            column["table"].replace("_", " "),
            column["column"],
            column["column"].replace("_", " "),
            str(column["column_info"].get("type", "")),
            column["description"],
            sample_text,
        ]
    )


def build_bm25_index(profile: dict[str, Any]) -> BM25Index:
    documents = []

    for column in iter_columns(profile):
        documents.append(
            BM25Document(
                key=column["qualified"],
                tokens=tokenize(build_column_document(column)),
                metadata=column,
            )
        )

    return BM25Index(documents)

