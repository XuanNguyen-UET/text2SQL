def extract_backtick_columns(text: str) -> list[str]:
    return [item.strip() for item in re.findall(r"`([^`]+)`", text or "") if item.strip()]


def extract_literal_candidates(question: str, evidence: str) -> list[str]:
    text = f"{question}\n{evidence or ''}"
    candidates = []

    for match in re.finditer(r"'([^']+)'|\"([^\"]+)\"", text):
        value = match.group(1) or match.group(2)
        if value:
            candidates.append(value.strip())

    for match in re.finditer(r"\b[A-Z][A-Za-z0-9_]+(?:\s+[A-Z][A-Za-z0-9_]+)+\b", question or ""):
        candidates.append(match.group(0).strip())

    output = []
    seen = set()

    for value in candidates:
        value = normalize_space(value)
        key = value.lower()

        if len(value) >= 2 and key not in seen:
            seen.add(key)
            output.append(value)

    return output


def match_literals_to_profile(profile: dict[str, Any], literals: list[str]) -> dict[str, list[dict[str, str]]]:
    result = {}

    for literal in literals:
        literal_key = literal.lower()
        result[literal] = []

        for column in iter_columns(profile):
            sample_values = column["column_info"].get("sample_values", []) or []

            for sample in sample_values:
                sample_text = str(sample)
                sample_key = sample_text.lower()

                if literal_key == sample_key or literal_key in sample_key or sample_key in literal_key:
                    result[literal].append(
                        {
                            "table": column["table"],
                            "column": column["column"],
                            "sample": sample_text,
                        }
                    )
                    break

    return result

def score_schema_columns(profile, question, evidence, logical_plan):
    query_text = "\n".join([question or "", evidence or "", logical_plan or ""])
    index = build_bm25_index(profile)
    bm25_scores = index.score(query_text)

    backtick_columns = set(extract_backtick_columns(f"{question}\n{evidence}"))
    literals = extract_literal_candidates(question, evidence)
    literal_matches = match_literals_to_profile(profile, literals)

    literal_match_pairs = set()
    for matches in literal_matches.values():
        for item in matches:
            literal_match_pairs.add((item["table"], item["column"]))

    query_lower = query_text.lower()
    rows = []

    for bm25_score, document in bm25_scores:
        meta = document.metadata
        table = meta["table"]
        column = meta["column"]

        boost = 0.0
        reasons = []

        if column in backtick_columns:
            boost += 8.0
            reasons.append("backtick_column")

        if column.lower() in query_lower:
            boost += 4.0
            reasons.append("column_name_mentioned")

        if table.lower() in query_lower:
            boost += 2.0
            reasons.append("table_name_mentioned")

        if (table, column) in literal_match_pairs:
            boost += 10.0
            reasons.append("sample_value_match")

        rows.append(
            {
                "table": table,
                "column": column,
                "qualified": f"{table}.{column}",
                "bm25_score": bm25_score,
                "boost": boost,
                "score": bm25_score + boost,
                "reasons": ",".join(reasons),
                "sample_values": meta["column_info"].get("sample_values", []),
                "description": meta["description"],
            }
        )

    return pd.DataFrame(rows).sort_values("score", ascending=False).reset_index(drop=True), literal_matches


def initial_schema_selection(profile, scored_columns):
    top_columns = scored_columns.head(TOP_COLUMN_CANDIDATES).copy()
    table_scores = top_columns.groupby("table")["score"].sum().sort_values(ascending=False)

    selected_tables = list(table_scores.head(MAX_TABLES).index)
    selected_schema = defaultdict(set)

    for table in selected_tables:
        table_columns = (
            top_columns[top_columns["table"] == table]
            .sort_values("score", ascending=False)
            .head(MAX_COLUMNS_PER_TABLE)
        )

        for column in table_columns["column"].tolist():
            selected_schema[table].add(column)

    pk_map = get_explicit_primary_key_map(profile)

    for table in list(selected_schema.keys()):
        for pk_column in pk_map.get(table, set()):
            selected_schema[table].add(pk_column)

    return dict(selected_schema)

def build_table_fk_graph(profile):
    graph = defaultdict(list)

    for edge in get_explicit_foreign_key_edges(profile):
        graph[edge["source_table"]].append((edge["target_table"], edge))
        graph[edge["target_table"]].append((edge["source_table"], edge))

    return dict(graph)


def find_shortest_table_path(graph, start_table, end_table):
    if start_table == end_table:
        return []

    queue = deque([(start_table, [])])
    visited = {start_table}

    while queue:
        current_table, path_edges = queue.popleft()

        for next_table, edge in graph.get(current_table, []):
            if next_table in visited:
                continue

            next_path = path_edges + [edge]

            if next_table == end_table:
                return next_path

            visited.add(next_table)
            queue.append((next_table, next_path))

    return []


def deduplicate_fk_edges(edges):
    seen = set()
    output = []

    for edge in edges:
        key = (edge["source"], edge["target"])
        if key not in seen:
            seen.add(key)
            output.append(edge)

    return output


def add_foreign_key_closure(profile, selected_schema):
    selected_schema = {table: set(columns) for table, columns in selected_schema.items()}
    initial_tables = set(selected_schema.keys())

    graph = build_table_fk_graph(profile)
    added_edges = []
    intermediate_tables = set()
    selected_table_list = list(initial_tables)

    for i in range(len(selected_table_list)):
        for j in range(i + 1, len(selected_table_list)):
            path_edges = find_shortest_table_path(graph, selected_table_list[i], selected_table_list[j])

            for edge in path_edges:
                source_table = edge["source_table"]
                target_table = edge["target_table"]

                if source_table not in initial_tables:
                    intermediate_tables.add(source_table)

                if target_table not in initial_tables:
                    intermediate_tables.add(target_table)

                selected_schema.setdefault(source_table, set()).add(edge["source_column"])
                selected_schema.setdefault(target_table, set()).add(edge["target_column"])
                added_edges.append(edge)

    for edge in get_explicit_foreign_key_edges(profile):
        if edge["source_table"] in selected_schema and edge["target_table"] in selected_schema:
            selected_schema[edge["source_table"]].add(edge["source_column"])
            selected_schema[edge["target_table"]].add(edge["target_column"])
            added_edges.append(edge)

    pk_map = get_explicit_primary_key_map(profile)

    for table in list(selected_schema.keys()):
        for pk_column in pk_map.get(table, set()):
            selected_schema[table].add(pk_column)

    if ADD_ALL_COLUMNS_FOR_INTERMEDIATE_TABLES:
        for table in intermediate_tables:
            selected_schema[table].update(profile["tables"][table]["columns"].keys())

    return selected_schema, deduplicate_fk_edges(added_edges), intermediate_tables

