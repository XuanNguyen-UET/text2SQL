def vote_select(candidates):
    groups = defaultdict(list)

    for candidate in candidates:
        execution = candidate.get("execution", {})
        if execution.get("status") == "success":
            key = json.dumps(execution.get("canonical", []), ensure_ascii=False)
            groups[key].append(candidate)

    if not groups:
        return "SELECT 1;"

    ranked = []
    for key, members in groups.items():
        rows = members[0]["execution"].get("rows", [])
        ranked.append(
            {
                "members": members,
                "vote_count": len(members),
                "is_empty": len(rows) == 0,
            }
        )

    ranked = sorted(
        ranked,
        key=lambda item: (not item["is_empty"], item["vote_count"]),
        reverse=True,
    )

    best_members = ranked[0]["members"]
    best_candidate = min(best_members, key=lambda item: len(item.get("sql", "")))

    return normalize_sql(best_candidate["sql"])


