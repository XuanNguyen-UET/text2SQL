def parse_json_object(text: str) -> dict[str, Any]:
    text = strip_think_blocks(text)
    match = re.search(r"\{.*\}", text, flags=re.DOTALL)

    if not match:
        return {}

    try:
        return json.loads(match.group(0))
    except Exception:
        return {}


def guard_action(action: str, summary: dict[str, Any]) -> str:
    if action not in VALID_ACTIONS:
        action = ""

    success_count = summary.get("success_count", 0)
    failed_count = summary.get("failed_count", 0)

    if action == "VOTE_SELECT" and success_count > 0:
        return "VOTE_SELECT"

    if action == "REPAIR_SQL" and failed_count > 0:
        return "REPAIR_SQL"

    if action == "REGENERATE_SQL":
        return "REGENERATE_SQL"

    if success_count > 0:
        return "VOTE_SELECT"

    if failed_count > 0:
        return "REPAIR_SQL"

    return "STOP_WITH_FALLBACK"


