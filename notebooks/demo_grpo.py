def split_qualified_name(name: str) -> tuple[str, str]:
    parts = str(name).split(".", 1)
    if len(parts) != 2:
        raise ValueError(f"Invalid qualified name: {name}")
    return parts[0], parts[1]


def count_tables_and_columns(profile: dict[str, Any]) -> tuple[int, int]:
    tables = profile.get("tables", {})
